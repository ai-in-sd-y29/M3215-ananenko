PROMPTS = {
    "study": STUDY_PROMPT,
    "translate": TRANSLATE_PROMPT,
    "exam": EXAM_PROMPT,
}


def system_prompt_for(mode: str) -> str:
    if mode not in MODES:
        mode = DEFAULT_MODE
    return PROMPTS[mode]


def mode_title(mode: str) -> str:
    return MODE_TITLES.get(mode, MODE_TITLES[DEFAULT_MODE])
